import { useRef } from "react";
import { QuestionMarkCircleIcon } from "@heroicons/react/24/outline";

export type ScoringConfig = {
  point_types?: {
    type: string;
    category: string;
    radii: number[];
    effective_radii?: number[];
  }[];
  system_weights?: Record<string, number>;
};

const names: Record<string, string> = {
  health: "Здоров’я",
  study: "Освіта",
  daily: "Щоденні потреби",
  mobility: "Транспорт",
  sport: "Спорт",
  enjoyment: "Дозвілля",
  food: "Харчування",
  security: "Безпека",
};

export default function ScoringGuide({
  config,
  compact = false,
}: {
  config: ScoringConfig;
  compact?: boolean;
}) {
  const dialog = useRef<HTMLDialogElement>(null);
  return (
    <>
      <button
        className={compact ? "debug-scoring-help" : undefined}
        aria-label="Як рахується оцінка"
        title="Як рахується оцінка"
        onClick={() => dialog.current?.showModal()}
      >
        {compact ? (
          <QuestionMarkCircleIcon aria-hidden="true" />
        ) : (
          "Як рахується оцінка"
        )}
      </button>
      <dialog
        ref={dialog}
        className="scoring-guide"
        aria-labelledby="scoring-guide-title"
        onClick={(event) => {
          if (event.target === event.currentTarget) dialog.current?.close();
        }}
      >
        <div className="scoring-guide-heading">
          <h2 id="scoring-guide-title">Як рахується оцінка</h2>
          <button
            autoFocus
            onClick={() => dialog.current?.close()}
            aria-label="Закрити гайд"
          >
            Закрити
          </button>
        </div>
        <div className="scoring-guide-body">
          <p>
            Точки → оцінки типів → оцінки категорій → загальна оцінка від 0 до
            100.
          </p>
          <nav aria-label="Зміст гайда">
            <a href="#guide-distance">Відстань і радіуси</a>
            <a href="#guide-categories">Ваги та категорії</a>
            <a href="#guide-overall">Загальна оцінка</a>
            <a href="#guide-transit">Транспорт</a>
            <a href="#guide-radii">Радіуси типів із БД</a>
          </nav>
          <h3 id="guide-distance">Відстань і радіуси</h3>
          <p>
            Для звичайного типу беруться три найближчі точки до центру гексагона
            серед усіх точок цього типу в БД. Вони можуть лежати за межами
            гексагона й видимої області мапи. Бал типу — середнє балів цих точок. Решта точок цього типу мають
            нульовий внесок у цей розрахунок.
          </p>
          <p>
            Відстань d вимірюється в метрах у локальному плоскому наближенні для
            Львова, за координатами точки й центру гексагона.
          </p>
          <pre>
            {
              "dy = (lat₁ − lat₂) × 111139\ndx = (lon₁ − lon₂) × 111139 × cos(49.84°)\nd = √(dx² + dy²)"
            }
          </pre>
          <p>
            Кожен тип має три радіуси r₁, r₂, r₃. Функція балів f(d) спадає з
            відстанню.
          </p>
          <div className="guide-table">
            <table>
              <thead>
                <tr>
                  <th>Відстань</th>
                  <th>Бали f(d)</th>
                </tr>
              </thead>
              <tbody>
                <tr>
                  <td>d ≤ r₁</td>
                  <td>100</td>
                </tr>
                <tr>
                  <td>r₁ &lt; d ≤ r₂</td>
                  <td>100 − 40 × (d − r₁) / (r₂ − r₁)</td>
                </tr>
                <tr>
                  <td>r₂ &lt; d ≤ r₃</td>
                  <td>60 − 40 × (d − r₂) / (r₃ − r₂)</td>
                </tr>
                <tr>
                  <td>d &gt; r₃</td>
                  <td>20 × exp(−(d − r₃) / r₃)</td>
                </tr>
              </tbody>
            </table>
          </div>
          <p>
            На межах r₁, r₂, r₃ отримуємо 100, 60, 20 балів. За r₃ вплив
            поступово згасає. Якщо точки цього типу немає, його бал дорівнює 0.
          </p>
          <p>
            Наприклад, за радіусів 300 / 600 / 1200 м точка на відстані 450 м
            дає 80 балів типу, а на 900 м — 40.
          </p>
          <h3 id="guide-categories">Ваги типів і оцінка категорії</h3>
          <pre>
            {
              "частка типу = вага типу / сума ваг типів категорії\nвнесок типу = частка типу × f(d)\nбал категорії = round(сума внесків типів)"
            }
          </pre>
          <p>
            Початкова вага кожного типу — 1. За однакових ваг кожен із N типів
            має частку 1/N. Ваги можна змінювати від 0 до 5. Нуль вимикає тип.
            Тип без точок бере участь у сумі ваг із нульовим балом. Якщо всі
            типи вимкнені, категорія отримує 0.
          </p>
          <p>
            Наприклад, два типи з балами 100 і 40 та вагами 1 і 1 дають 70 балів
            категорії. Ваги 2 і 1 дають 80. Внесок точки в картці — її частина
            бала категорії до округлення.
          </p>
          <p>
            Оцінки категорій округлюються до цілих за правилом Python round —
            точна половина округлюється до найближчого парного цілого.
          </p>
          <h3 id="guide-overall">Загальна оцінка</h3>
          <p>
            Для активної категорії до користувацької ваги додається системна.
            Після нормалізації використовується зважене геометричне середнє.
          </p>
          <pre>
            {
              "Wᵢ = системна вагаᵢ + користувацька вагаᵢ\nαᵢ = Wᵢ / сума W активних категорій\nS = добуток (бал категоріїᵢ ^ αᵢ)\nрезультат = floor(S + 0.5)"
            }
          </pre>
          <p>
            Користувацька вага 0 повністю вимикає категорію, включно з її
            системною вагою. Початково користувацькі ваги дорівнюють 1. Нульовий
            бал будь-якої активної категорії дає загальну оцінку 0. Якщо всі
            категорії вимкнені, результат також 0.
          </p>
          <p>
            Наприклад, дві категорії з однаковими нормалізованими вагами та
            балами 100 і 64 дають √(100 × 64) = 80.
          </p>
          {config.system_weights && (
            <div className="guide-table">
              <table>
                <caption>Поточні системні ваги</caption>
                <thead>
                  <tr>
                    <th>Категорія</th>
                    <th>Вага</th>
                  </tr>
                </thead>
                <tbody>
                  {Object.entries(config.system_weights).map(([key, value]) => (
                    <tr key={key}>
                      <td>{names[key] || key}</td>
                      <td>{value}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
          <h3 id="guide-transit">Транспортна складова</h3>
          <p>
            У категорії «Транспорт» звичайні POI рахуються за найближчою точкою.
            Компонент gtfs_stop оцінює доступність мережі громадського
            транспорту.
          </p>
          <ol>
            <li>
              Беруться всі зупинки в межах r₃. Для кожної вага доступу дорівнює
              f(d)/100. Якщо таких зупинок немає, береться найближча й
              застосовується штраф 0.3.
            </li>
            <li>
              Для кожної вибраної зупинки знаходяться інші зупинки на пов’язаних
              маршрутах. Для кожного пункту призначення зберігається максимальна
              вага доступу серед способів до нього дістатися.
            </li>
            <li>
              Ваги унікальних пунктів призначення підсумовуються та множаться на
              штраф. Отримуємо значення R.
            </li>
          </ol>
          <pre>{"бал gtfs_stop = min(100, 100 × ln(1 + R) / ln(20))"}</pre>
          <p>
            Цей бал входить у категорію як окремий тип зі своєю вагою. Внесок
            мережі спільний для зупинок. Формула використовує зв’язки маршрутів
            і зупинок, без часу поїздки та частоти рейсів.
          </p>
          <h3 id="guide-radii">Поточні радіуси типів із БД</h3>
          <p>
            У таблиці наведено радіуси, які реально застосовує розрахунок, у
            метрах. Для порожнього або нульового значення використовується
            запасне — 300 / 600 / 1200 для звичайних категорій, 200 / 400 / 800
            для транспортних POI та 200 / 400 / 700 для gtfs_stop.
          </p>
          {config.point_types?.length ? (
            <div className="guide-table">
              <table>
                <thead>
                  <tr>
                    <th>Тип</th>
                    <th>Категорія</th>
                    <th>r₁, м</th>
                    <th>r₂, м</th>
                    <th>r₃, м</th>
                  </tr>
                </thead>
                <tbody>
                  {config.point_types.map((type) => (
                    <tr key={type.type}>
                      <td>{type.type}</td>
                      <td>{names[type.category] || type.category}</td>
                      {(type.effective_radii || type.radii).map((r, index) => (
                        <td key={index}>{r}</td>
                      ))}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          ) : (
            <p>
              Радіуси конфігурації недоступні. Перезавантажте сторінку та
              увійдіть знову.
            </p>
          )}
          <h3>Як читати дебагер</h3>
          <p>
            «Збережене» об’єднує категорії з БД з початковими вагами. «Свіже»
            заново рахує категорії з поточних точок і початкових ваг.
            «Експеримент» застосовує ваші ваги. «Різниця» на мапі показує
            експеримент мінус свіжий результат.
          </p>
          <p>
            Змініть ваги та натисніть «Перерахувати», щоб застосувати їх до
            видимої області. Експеримент діє в пам’яті сторінки. «Скинути ваги»
            повертає початкові налаштування.
          </p>
        </div>
      </dialog>
    </>
  );
}
